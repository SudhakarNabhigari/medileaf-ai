"""Page 6 — Model Analytics displaying genuine training, calibration, and OOD evaluation metrics."""

from __future__ import annotations

import json

import pandas as pd
import streamlit as st

from src.config import FIGURES_REPORTS_DIR, METRICS_REPORTS_DIR, TRAINING_HISTORY_PATH


def render() -> None:
    st.markdown("## 📊 Model Analytics")
    st.caption("Comprehensive evaluation of the leaf identification model")

    st.markdown(
        """
        <div class="medileaf-hero animate-enter">
          <h1 style="font-size:1.85rem; font-weight:800; margin:0;">
            Model Performance <span class="lime-accent">Analytics</span>
          </h1>
          <p style="margin:0.35rem 0 0 0; color:#E2F5E9; font-size:0.94rem;">
            Evaluation results, learning curves, confusion matrix, and OOD detection performance for MediLeaf AI (ResNet50 Transfer Learning).
          </p>
        </div>
        """,
        unsafe_allow_html=True,
    )

    eval_path = METRICS_REPORTS_DIR / "evaluation_summary.json"
    has_eval = eval_path.exists()
    metrics = json.loads(eval_path.read_text(encoding="utf-8")) if has_eval else {}

    if not has_eval:
        st.info(
            "**Evaluation Results Not Available (Training Pending):** Genuine model metrics will populate "
            "automatically from `reports/metrics/evaluation_summary.json` and `artifacts/training_history.csv` "
            "once `src/train.py` and `src/evaluate.py` execute."
        )

    c1, c2, c3, c4, c5, c6 = st.columns(6)
    items = [
        (c1, f"{metrics['closed_set_accuracy']*100:.2f}%" if has_eval else "Pending", "Accuracy"),
        (c2, f"{metrics['macro_precision']:.2f}" if has_eval else "Pending", "Precision"),
        (c3, f"{metrics['macro_recall']:.2f}" if has_eval else "Pending", "Recall"),
        (c4, f"{metrics['macro_f1']:.2f}" if has_eval else "Pending", "F1-Score"),
        (c5, f"{metrics['known_coverage']:.2f}" if has_eval else "Pending", "Coverage"),
        (c6, f"{metrics['known_rejection_rate']:.2f}" if has_eval else "Pending", "Rejection Rate"),
    ]
    for col, val, label in items:
        with col:
            st.markdown(
                f"""
                <div class="medileaf-card animate-enter">
                  <div class="medileaf-metric-label">{label}</div>
                  <div class="medileaf-metric-val" style="font-size:1.25rem;">{val}</div>
                </div>
                """,
                unsafe_allow_html=True,
            )

    st.markdown("<div style='height:1rem;'></div>", unsafe_allow_html=True)
    col_left, col_mid, col_right = st.columns([1.15, 1.15, 1.0], gap="medium")

    with col_left:
        st.markdown('<div class="medileaf-card">', unsafe_allow_html=True)
        st.markdown("#### Training & Validation Accuracy")
        curves_img = FIGURES_REPORTS_DIR / "training_curves.png"
        if curves_img.exists():
            st.image(str(curves_img), use_container_width=True)
        elif TRAINING_HISTORY_PATH.exists():
            hist = pd.read_csv(TRAINING_HISTORY_PATH)
            st.line_chart(hist.set_index("epoch")[["train_acc", "val_acc"]])
        else:
            st.caption("Training curves pending — generated by `src/train.py`.")
        st.markdown("</div>", unsafe_allow_html=True)

    with col_mid:
        st.markdown('<div class="medileaf-card">', unsafe_allow_html=True)
        st.markdown("#### Confusion Matrix")
        cm_img = FIGURES_REPORTS_DIR / "confusion_matrix.png"
        if cm_img.exists():
            st.image(str(cm_img), use_container_width=True)
        else:
            st.caption("Confusion matrix pending — generated by `src/evaluate.py`.")
        st.markdown("</div>", unsafe_allow_html=True)

    with col_right:
        st.markdown('<div class="medileaf-card">', unsafe_allow_html=True)
        st.markdown("#### OOD Evaluation")
        ood_rows = [
            ("OOD AUROC (MSP)", f"{metrics['msp_ood_auroc']:.3f}" if "msp_ood_auroc" in metrics else "Pending"),
            ("OOD AUPR (MSP)", f"{metrics['msp_ood_aupr']:.3f}" if "msp_ood_aupr" in metrics else "Pending"),
            ("OOD AUROC (Energy)", f"{metrics['energy_ood_auroc']:.3f}" if "energy_ood_auroc" in metrics else "Pending"),
            ("Selective Accuracy", f"{metrics['selective_accuracy']:.3f}" if "selective_accuracy" in metrics else "Pending"),
            ("OOD Rejection Rate", f"{metrics['ood_rejection_rate']:.3f}" if "ood_rejection_rate" in metrics else "Pending"),
        ]
        for label, val in ood_rows:
            st.markdown(f"**{label}:** `{val}`")
        st.markdown("</div>", unsafe_allow_html=True)
